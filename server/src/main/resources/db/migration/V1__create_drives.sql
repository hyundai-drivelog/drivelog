CREATE TABLE drives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE NOT NULL,
    duration_seconds BIGINT NOT NULL,
    distance_km NUMERIC(12, 3) NOT NULL,
    average_efficiency NUMERIC(12, 3),
    efficiency_unit VARCHAR(16),
    source_type VARCHAR(8) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT drives_time_order CHECK (ended_at >= started_at),
    CONSTRAINT drives_duration CHECK (duration_seconds >= 0 AND duration_seconds = FLOOR(EXTRACT(EPOCH FROM (ended_at - started_at)))),
    CONSTRAINT drives_distance CHECK (distance_km >= 0),
    CONSTRAINT drives_efficiency CHECK (
        (average_efficiency IS NULL AND efficiency_unit IS NULL) OR
        (average_efficiency IS NOT NULL AND average_efficiency > 0 AND efficiency_unit IS NOT NULL AND efficiency_unit IN ('km/L', 'km/kWh'))
    ),
    CONSTRAINT drives_source CHECK (source_type IN ('MOCK', 'PLEOS'))
);

CREATE INDEX drives_recent_idx ON drives (started_at DESC, id DESC);
